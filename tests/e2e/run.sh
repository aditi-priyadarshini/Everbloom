#!/bin/bash
# End-to-end journeys against a REAL stack: Postgres -> PostgREST -> Flask app (no mocks).
#   sudo bash tests/e2e/run.sh fresh     # uuid ids (new project)
#   sudo bash tests/e2e/run.sh legacy    # integer custom_requests.id (like an older live DB)
# Needs (Ubuntu/Debian): postgresql-16, the PostgREST binary at /tmp/pgrst/postgrest, python deps.
# Everything runs in a throw-away cluster under /tmp. It NEVER touches Supabase or production.
set -u
E=$(cd "$(dirname "$0")" && pwd); R=$(cd "$E/../.." && pwd); PGBIN=${PGBIN:-/usr/lib/postgresql/16/bin}
export E2E_MODE=${1:-fresh}
pkill -f '/tmp/pgrst/postgre[s]t'; pkill -f 'e2e/prox[y].py'
su postgres -c "$PGBIN/pg_ctl -D /tmp/pgdata stop -m immediate" >/dev/null 2>&1; pkill -u postgres 2>/dev/null; sleep 1
rm -rf /tmp/pgdata /tmp/.s.PGSQL.5433*; mkdir /tmp/pgdata; chown postgres /tmp/pgdata
chmod -R a+rX "$E" "$R/supabase" 2>/dev/null
su postgres -c "$PGBIN/initdb -D /tmp/pgdata -A trust >/dev/null && $PGBIN/pg_ctl -D /tmp/pgdata -o '-p 5433 -k /tmp -c fsync=off' -l /tmp/pg.log start >/dev/null"
for i in $(seq 1 20); do su postgres -c "pg_isready -h /tmp -p 5433" >/dev/null 2>&1 && break; sleep 1; done
P(){ su postgres -c "psql -h /tmp -p 5433 -q -X $*" 2>&1; }
echo "create role service_role nologin bypassrls; create role anon nologin; create role authenticated nologin; create database e2e;" > /tmp/e2e_roles.sql; chmod 644 /tmp/e2e_roles.sql
P -f /tmp/e2e_roles.sql; P -d e2e -f "$E/storage_stub.sql"
if [ "$E2E_MODE" = "legacy" ]; then
  M=$R/supabase/migrations
  sed 's/create table if not exists custom_requests (id uuid primary key default gen_random_uuid()/create table if not exists custom_requests (id bigint generated by default as identity primary key/' "$M/001_legacy_baseline.sql" > /tmp/001_legacy_int.sql; chmod 644 /tmp/001_legacy_int.sql
  for f in /tmp/001_legacy_int.sql $M/00[2-9]*.sql $M/01[01]*.sql ${E2E_REPAIR:-$R/supabase/EXISTING_PROJECT_REPAIR_012_TO_017.sql}; do P -d e2e -f $f | grep -i error; done
else
  P -d e2e -v ON_ERROR_STOP=1 -f "$R/supabase/FRESH_PROJECT_SQL_EDITOR_SETUP.sql" | grep -i error
fi
echo "insert into categories(name,slug) values ('Bouquets','bouquets') on conflict do nothing;" > /tmp/e2e_cat.sql; chmod 644 /tmp/e2e_cat.sql; P -d e2e -f /tmp/e2e_cat.sql
P -d e2e -f "$E/grants.sql" | grep -i error
(/tmp/pgrst/postgrest "$E/pgrst.conf" >/tmp/pgrst.log 2>&1 &); (python "$E/proxy.py" >/tmp/proxy.log 2>&1 &)
for i in $(seq 1 40); do [ "$(curl -s -o /dev/null -m 2 -w '%{http_code}' http://127.0.0.1:3000/)" = "200" ] && break; sleep 1; done
export JWT=$(python - <<'EOF'
import hmac,hashlib,base64,json
b=lambda x:base64.urlsafe_b64encode(x).rstrip(b'=')
h=b(json.dumps({'alg':'HS256','typ':'JWT'}).encode()); p=b(json.dumps({'role':'service_role'}).encode())
print((h+b'.'+p+b'.'+b(hmac.new(b'e2e-test-secret-at-least-32-characters-long!!',h+b'.'+p,hashlib.sha256).digest())).decode())
EOF
)
export SUPABASE_URL=http://127.0.0.1:8081 SUPABASE_SERVICE_ROLE_KEY=$JWT SECRET_KEY=e2e-secret-key-that-is-long-enough-32chars APP_ENV=development SITE_URL=http://localhost:5000 MAIL_USERNAME=shop@example.com MAIL_PASSWORD=x
cd "$R" && python "$E/journeys.py" 2>&1 | grep -v "email SKIP\|email OK\|email ERROR\|^Supabase"
pkill -f '/tmp/pgrst/postgre[s]t'; pkill -f 'e2e/prox[y].py'; su postgres -c "$PGBIN/pg_ctl -D /tmp/pgdata stop -m fast" >/dev/null 2>&1
